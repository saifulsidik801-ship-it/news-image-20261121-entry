def draw_map(cv, x, y, w, h):
    """Stylised world map with numbered pins (number = story on this page).

    Continent polygons and pins are drawn in a 288x220 reference frame
    and scaled to (w, h), so the map keeps its shape at any size.
    """
    cv.fill(x, y, w, h, NAVY)
    land = (222, 210, 170)
    sx = w / 288.0
    sy = h / 220.0
    polys = [
        [(18, 38), (62, 22), (108, 30), (112, 58), (86, 78), (52, 72), (24, 58)],
        [(78, 92), (108, 88), (118, 118), (98, 152), (82, 128)],
        [(138, 32), (164, 24), (176, 42), (156, 56), (138, 48)],
        [(140, 68), (168, 62), (180, 92), (162, 124), (144, 98)],
        [(178, 28), (248, 22), (266, 48), (242, 72), (202, 66), (184, 48)],
        [(232, 138), (264, 132), (270, 152), (240, 158)],
    ]
    for p in polys:
        cv.poly([(x + int(px * sx), y + int(py * sy)) for px, py in p], land)
    pins = [(172, 48, "1"), (190, 72, "2"), (92, 122, "3"), (152, 32, "4"),
            (214, 84, "5"), (206, 58, "6"), (42, 54, "7"), (238, 48, "8"),
            (254, 84, "9"), (252, 148, "10"), (140, 110, "11"),
            (30, 62, "12"), (272, 166, "13")]
    for px, py, n in pins:
        cxp = x + int(px * sx)
        cyp = y + int(py * sy)
        cv.circle(cxp, cyp, 9, RED2)
        draw_text(cv, cxp - text_w(n, "B16") // 2, cyp - 8, n, "B16", WHITE)
    draw_text(cv, x + 6, y + h - 40, "Each number is", "R16", WHITE)
    draw_text(cv, x + 6, y + h - 21, "the story.", "R16", WHITE)


