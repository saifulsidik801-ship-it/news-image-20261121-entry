def build_image():
    cv = Canvas(W, H, PAPER)
    M = 20
    RW = W - 2 * M

    # Top strip.
    y = 10
    draw_text(cv, M, y, "THE WORLD IN ONE DAY", "B16", RED)
    right = "35 STORIES • 7 REGIONS • EVERY ONE DATED"
    draw_text(cv, M + RW - text_w(right, "R16"), y, right, "R16", INK)
    y += line_h("R16")
    cv.hline(M, y, RW, INK, 2)
    y += 6

    # Huge date.
    date = "Saturday 21 November 2026"
    draw_text(cv, W // 2 - text_w(date, "D52") // 2, y, date, "D52", INK)
    y += line_h("D52")
    draw_text_centered(cv, W // 2, y,
                       "COP31 past deadline • Missiles shot down over "
                       "Saudi Arabia • Quake shakes Peru", "R16", INK)
    y += line_h("R16")
    cv.hline(M, y, RW, INK, 2)
    y += 6

    # Numbers row: 6 cells.
    cw = RW // 6
    for i, (num, caps) in enumerate(NUMBERS):
        cx = M + i * cw
        draw_text(cv, cx + (cw - text_w(num, "B26")) // 2, y, num, "B26", NAVY2)
        cy = y + line_h("B26") + 3
        for cap in caps:
            draw_text(cv, cx + (cw - text_w(cap, "R16")) // 2, cy, cap, "R16",
                      GREY)
            cy += line_h("R16")
        if i:
            cv.vline(cx, y + 2, 88, MIDGREY, 1)
    y += line_h("B26") + 3 + 3 * line_h("R16")

    # Region bar.
    rx = M
    for label, col in REGIONS:
        wch = text_w(label, "B16") + 16
        cv.fill(rx, y, wch, 20, col)
        draw_text(cv, rx + 8, y + 1, label, "B16", WHITE)
        rx += wch + 8
    y += 21

    # Three illustrated leads. v5: pictures ~2x taller (106px) to match
    # the top-1 entry; summaries at R16 so the taller pictures fit.
    LEAD_H = 106
    lw = (RW - 24) // 3
    lead_bottom = y
    for i, (banner, tag, kick, head, summ, scene) in enumerate(LEADS):
        lx = M + i * (lw + 12)
        scene(cv, lx, y, lw, LEAD_H)
        cv.fill(lx, y, text_w(banner, "B16") + 12, 20, RED)
        draw_text(cv, lx + 6, y + 1, banner, "B16", WHITE)
        cv.fill(lx, y + LEAD_H - 20, text_w(tag, "B16") + 12, 20, WHITE)
        draw_text(cv, lx + 6, y + LEAD_H - 19, tag, "B16", INK)
        ky = y + LEAD_H + 4
        draw_text(cv, lx, ky, kick, "B16", RED)
        hy = ky + line_h("B16") + 4
        n_head = len(wrap(head, lw, "B26"))
        draw_para(cv, lx, hy, head, lw, "B26", INK, leading=line_h("B26"))
        sy = hy + n_head * line_h("B26") + 4
        n_summ = len(wrap(summ, lw, "R16"))
        draw_para(cv, lx, sy, summ, lw, "R16", (60, 60, 60),
                  leading=line_h("R16"))
        lead_bottom = max(lead_bottom, sy + n_summ * line_h("R16"))
    y = lead_bottom + 4

    # Ten medium stories, 2 rows x 5. v5: pictures ~2x taller (50px) with
    # a red banner label on top, as in the top-1 entry; summaries at R16.
    MED_H = 50
    MED_PITCH = MED_H + 117
    mw = (RW - 40) // 5
    for row in range(2):
        for col in range(5):
            banner, kick, head, summ, scene = MEDIUM[row * 5 + col]
            mx = M + col * (mw + 10)
            my = y + row * MED_PITCH
            scene(cv, mx, my, mw, MED_H)
            cv.fill(mx, my, text_w(banner, "B16") + 12, 18, RED)
            draw_text(cv, mx + 6, my + 1, banner, "B16", WHITE)
            draw_text(cv, mx, my + MED_H + 2, kick, "B16", RED)
            hy = my + MED_H + 2 + line_h("B16") + 3
            n_head = len(wrap(head, mw, "B20"))
            draw_para(cv, mx, hy, head, mw, "B20", INK,
                      leading=line_h("B20"))
            sy = hy + n_head * line_h("B20") + 3
            n_summ = len(wrap(summ, mw, "R16"))
            draw_para(cv, mx, sy, summ, mw, "R16", (60, 60, 60),
                      leading=line_h("R16"))
    y += 2 * MED_PITCH + 4

    # Map + ALSO list. v5: map shorter (140px) and wider (240px), ALSO in
    # 3 columns so the section shrinks and frees room for the pictures.
    map_w, map_h = 240, 140
    ax = M + map_w + 16
    acw = (RW - map_w - 16) // 3
    draw_text(cv, M, y, "WHERE IT HAPPENED", "B16", RED)
    draw_text(cv, ax, y, "ALSO ON SATURDAY 21 NOVEMBER - 22 MORE STORIES",
              "B16", RED)
    y += line_h("B16")
    draw_map(cv, M, y, map_w, map_h)
    for i, item in enumerate(ALSO):
        ix = ax + (i // 8) * acw
        iy = y + (i % 8) * 17
        num = item.split(" ", 1)[0]
        rest = item[len(num) + 1:]
        draw_text(cv, ix, iy, num + " ", "B16", RED)
        draw_text(cv, ix + text_w(num + " ", "B16"), iy, rest, "R16", INK)
    y += map_h + 2

    # DATE CHECK box.
    lines = wrap(DATE_CHECK, RW - 16, "R16")
    box_h = len(lines) * line_h("R16") + 6
    cv.rect(M, y, RW, box_h, RED, 2)
    ty = y + 3
    for ln in lines:
        draw_text(cv, M + 8, ty, ln, "R16", INK)
        ty += line_h("R16")
    y += box_h + 3

    # Footer.
    draw_text_centered(cv, W // 2, y,
                       "Every story happened, or was first reported, on "
                       "Saturday 21 November 2026.", "R16", INK)
    y += line_h("R16")
    if y + line_h("R16") <= H - 4:
        draw_text_centered(cv, W // 2, y,
                           "Sources: AFP, Reuters, AP, Al Jazeera, Dawn, "
                           "USGS, IGP, ABC, CNN.", "R16", GREY)
        y += line_h("R16")
    print("final y:", y)
    return png_bytes(cv)


