class Canvas:
    def __init__(self, w, h, bg):
        self.w = w
        self.h = h
        self.px = bytearray(bg * (w * h))

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i], self.px[i + 1], self.px[i + 2] = c

    def blit(self, x, y, w, h, bmp, color):
        """Alpha-blit a grayscale glyph bitmap (0-255) in the given color.

        bmp is row-major bytes, w*h long.  Pixels with alpha 0 are
        skipped, 255 is written directly, anything else is blended
        against the current pixel so text stays smooth over any
        background (paper, coloured boxes, scenes).
        """
        r, g, b = color
        px = self.px
        W = self.w
        H = self.h
        for row in range(h):
            yy = y + row
            if yy < 0 or yy >= H:
                continue
            base = row * w
            for col in range(w):
                a = bmp[base + col]
                if a == 0:
                    continue
                xx = x + col
                if xx < 0 or xx >= W:
                    continue
                i = (yy * W + xx) * 3
                if a == 255:
                    px[i], px[i + 1], px[i + 2] = r, g, b
                else:
                    px[i] = (a * r + (255 - a) * px[i]) // 255
                    px[i + 1] = (a * g + (255 - a) * px[i + 1]) // 255
                    px[i + 2] = (a * b + (255 - a) * px[i + 2]) // 255

    def fill(self, x, y, w, h, c):
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(self.w, x + w)
        y1 = min(self.h, y + h)
        for yy in range(y0, y1):
            base = (yy * self.w + x0) * 3
            for xx in range(x0, x1):
                i = base + (xx - x0) * 3
                self.px[i], self.px[i + 1], self.px[i + 2] = c

    def rect(self, x, y, w, h, c, t=1):
        self.fill(x, y, w, t, c)
        self.fill(x, y + h - t, w, t, c)
        self.fill(x, y, t, h, c)
        self.fill(x + w - t, y, t, h, c)

    def hline(self, x, y, w, c, t=1):
        self.fill(x, y, w, t, c)

    def vline(self, x, y, h, c, t=1):
        self.fill(x, y, t, h, c)

    def line(self, x0, y0, x1, y1, c, t=1):
        dx = x1 - x0
        dy = y1 - y0
        steps = max(abs(dx), abs(dy), 1)
        for s in range(steps + 1):
            x = x0 + dx * s // steps
            y = y0 + dy * s // steps
            self.fill(x - t // 2, y - t // 2, t, t, c)

    def circle(self, cx, cy, r, c, filled=True):
        for yy in range(cy - r, cy + r + 1):
            for xx in range(cx - r, cx + r + 1):
                d = (xx - cx) ** 2 + (yy - cy) ** 2
                if filled:
                    if d <= r * r:
                        self.set(xx, yy, c)
                else:
                    if r * r - 2 * r <= d <= r * r:
                        self.set(xx, yy, c)

    def poly(self, pts, c):
        # Scanline fill of a simple polygon.
        ys = [p[1] for p in pts]
        for y in range(min(ys), max(ys) + 1):
            xs = []
            n = len(pts)
            for i in range(n):
                x0, y0 = pts[i]
                x1, y1 = pts[(i + 1) % n]
                if (y0 <= y < y1) or (y1 <= y < y0):
                    xs.append(x0 + (y - y0) * (x1 - x0) // (y1 - y0))
            xs.sort()
            for k in range(0, len(xs) - 1, 2):
                for x in range(xs[k], xs[k + 1] + 1):
                    self.set(x, y, c)


# ---------------------------------------------------------------- text
def text_w(s, font):
    """Pixel width of string s in the given font (sum of advances)."""
    _, _, glyphs = FONTS[font]
    q = glyphs["?"]
    return sum(glyphs.get(ch, q)[0] for ch in s)


def draw_text(cv, x, y, s, font, color):
    """Draw text; y is the TOP of the line (top of the ascender).

    Each glyph is alpha-blitted at its ink offset (x0, y0) from the pen
    origin, then the pen advances by the glyph advance, so baselines
    line up across mixed case, digits and descenders.
    """
    _, _, glyphs = FONTS[font]
    q = glyphs["?"]
    for ch in s:
        adv, x0, y0, w, h, bmp = glyphs.get(ch, q)
        if w and h:
            cv.blit(x + x0, y + y0, w, h, bmp, color)
        x += adv
    return x


def draw_text_centered(cv, cx, y, s, font, color):
    draw_text(cv, cx - text_w(s, font) // 2, y, s, font, color)


def wrap(s, max_w, font):
    words = s.split(" ")
    lines = []
    cur = ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if text_w(trial, font) <= max_w or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def draw_para(cv, x, y, s, max_w, font, color, leading=None):
    if leading is None:
        leading = line_h(font)
    lines = wrap(s, max_w, font)
    for ln in lines:
        draw_text(cv, x, y, ln, font, color)
        y += leading
    return y


# ---------------------------------------------------------------- png
def png_bytes(cv):
    raw = bytearray()
    stride = cv.w * 3
    for y in range(cv.h):
        raw.append(0)
        raw += cv.px[y * stride:(y + 1) * stride]
    comp = zlib.compress(bytes(raw), 6)

    def chunk(tag, data):
        out = struct.pack(">I", len(data)) + tag + data
        out += struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        return out

    ihdr = struct.pack(">IIBBBBB", cv.w, cv.h, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", comp)
        + chunk(b"IEND", b"")
    )

